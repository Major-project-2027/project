"""Evaluates the EXISTING PRODUCTION emotion model against a SECOND,
independent real labelled dataset already present in this project:
datasets/raw/ckplus/ (the CK+ facial-expression dataset, folder-per-class
real images -- not synthetic, not generated by this script).

READ-ONLY / EVALUATION-ONLY -- see evaluate_emotion_fer2013.py's
docstring for the same guarantees (no retraining, no production code
touched, no fabricated labels).

IMPORTANT CLASS-MAPPING HONESTY NOTE:
CK+'s folders are: anger, contempt, disgust, fear, happy, sadness,
surprise. The production model's 7 output classes are: Angry, Disgust,
Fear, Happy, Sad, Surprise, Neutral (see ai_service.py's emotion_labels).

- "contempt" (54 real images) has NO corresponding model class and is
  EXCLUDED from evaluation -- it is not silently mapped to the nearest
  label, which would fabricate a mapping CK+ itself doesn't assert.
- CK+ provides NO "neutral"-labelled images at all, so this dataset
  cannot evaluate the model's Neutral-class recall/precision. This is
  reported explicitly, not glossed over.
- The other 6 CK+ classes map 1:1 onto 6 of the model's 7 classes
  (sadness -> Sad) and ARE evaluated.
"""

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import cv2
import numpy as np

_PROJECT_ROOT = Path(__file__).resolve().parents[2]
EMOTION_MODEL_PATH = _PROJECT_ROOT / "ml_models" / "emotion_recognition" / "emotion_model.keras"
CKPLUS_DIR = _PROJECT_ROOT / "datasets" / "raw" / "ckplus"
REPORT_PATH = Path(__file__).resolve().parent / "reports" / "emotion_ckplus_report.json"


def _parse_args():
    # Optional override so this script can also evaluate a CANDIDATE
    # model before it is promoted to production -- defaults to the exact
    # same production path as before when not given.
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-path", type=str, default=None)
    parser.add_argument("--report-name", type=str, default=None)
    return parser.parse_args()

EMOTION_LABELS = ["Angry", "Disgust", "Fear", "Happy", "Sad", "Surprise", "Neutral"]

# Real folder name -> real model class name. "contempt" deliberately
# omitted (no matching model class -- see module docstring).
FOLDER_TO_LABEL = {
    "anger": "Angry",
    "disgust": "Disgust",
    "fear": "Fear",
    "happy": "Happy",
    "sadness": "Sad",
    "surprise": "Surprise",
}

IMG_SIZE = 224
BATCH_SIZE = 32


def _load_ckplus():
    """Loads every real image from the usable CK+ folders (see
    FOLDER_TO_LABEL) preprocessed EXACTLY the way ai_service.py feeds a
    face crop to this model: cv2.resize -> float32/255.0. Returns
    (images, true_label_indices, excluded_count)."""

    images = []
    true_idx = []
    excluded = 0

    for folder in sorted(CKPLUS_DIR.iterdir()):
        if not folder.is_dir():
            continue
        label = FOLDER_TO_LABEL.get(folder.name)
        if label is None:
            excluded += sum(1 for f in folder.iterdir() if f.is_file())
            continue
        label_idx = EMOTION_LABELS.index(label)
        for f in sorted(folder.iterdir()):
            if not f.is_file():
                continue
            img = cv2.imread(str(f))
            if img is None:
                continue
            img = cv2.resize(img, (IMG_SIZE, IMG_SIZE))
            img = img.astype("float32") / 255.0
            images.append(img)
            true_idx.append(label_idx)

    return np.array(images, dtype="float32"), np.array(true_idx, dtype="int64"), excluded


def main():
    args = _parse_args()
    model_path = Path(args.model_path) if args.model_path else EMOTION_MODEL_PATH
    report_path = (
        REPORT_PATH.parent / args.report_name if args.report_name else REPORT_PATH
    )

    result = {
        "component": "Emotion Recognition -- second independent real dataset",
        "model_path": str(model_path),
        "evaluated_at": datetime.now(timezone.utc).isoformat(),
        "dataset": "CK+ (real, public), classes: anger/disgust/fear/happy/sadness/surprise (contempt excluded, no Neutral images available)",
    }

    print("=" * 70)
    print("EMOTION MODEL EVALUATION -- real CK+ dataset (independent of FER2013)")
    print(f"Model: {model_path}")
    print("=" * 70)

    try:
        from tensorflow.keras.models import load_model
        model = load_model(model_path)
        result["model_runtime_status"] = "LOADED_OK"
        print(f"MODEL RUNTIME STATUS: LOADED OK ({model_path})")
    except Exception as exc:  # noqa: BLE001
        result["model_runtime_status"] = "FAILED_TO_LOAD"
        result["model_load_error"] = str(exc)[:500]
        result["status"] = "NOT EVALUATABLE -- MODEL FAILED TO LOAD"
        print("MODEL RUNTIME STATUS: FAILED TO LOAD")
        print(f"  error: {str(exc)[:300]}")
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(json.dumps(result, indent=2))
        print(f"\nSaved report to {report_path}")
        return

    print("\nLoading real CK+ images...")
    X, y_true, excluded = _load_ckplus()
    print(f"Usable labelled images: {len(X)}  (excluded 'contempt': {excluded}, no model class)")
    print("NOTE: CK+ has no Neutral-labelled images -- Neutral cannot be assessed from this dataset.")

    print("\nRunning real inference in batches...")
    preds = []
    for start in range(0, len(X), BATCH_SIZE):
        batch_preds = model.predict(X[start:start + BATCH_SIZE], verbose=0)
        preds.append(batch_preds)
    preds = np.concatenate(preds, axis=0)
    y_pred = np.argmax(preds, axis=1)

    from sklearn.metrics import (
        accuracy_score, precision_recall_fscore_support,
        classification_report, confusion_matrix,
    )

    present_labels = sorted(set(y_true.tolist()))
    present_names = [EMOTION_LABELS[i] for i in present_labels]

    accuracy = accuracy_score(y_true, y_pred)
    macro_p, macro_r, macro_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=present_labels, average="macro", zero_division=0
    )
    per_class = classification_report(
        y_true, y_pred, labels=present_labels, target_names=present_names,
        output_dict=True, zero_division=0,
    )
    cm = confusion_matrix(y_true, y_pred, labels=present_labels).tolist()

    print("\n" + "=" * 70)
    print(f"TEST ACCURACY (6-class, CK+):  {accuracy:.4f}  ({accuracy*100:.2f}%)")
    print(f"MACRO precision/recall/F1:     {macro_p:.4f} / {macro_r:.4f} / {macro_f1:.4f}")
    print("\nPer-class F1:")
    for label in present_names:
        print(f"  {label:10s}: {per_class[label]['f1-score']:.4f}  (support={int(per_class[label]['support'])})")
    print("\nConfusion matrix (rows=true, cols=predicted):")
    print("        " + " ".join(f"{l[:4]:>6s}" for l in present_names))
    for label, row in zip(present_names, cm):
        print(f"{label:8s}" + " ".join(f"{v:6d}" for v in row))
    print("=" * 70)

    result.update({
        "status": "VALID PROJECT-SPECIFIC METRIC (6 of 7 classes -- no Neutral ground truth in this dataset)",
        "test_samples": int(len(X)),
        "excluded_no_class_match": int(excluded),
        "accuracy": round(float(accuracy), 4),
        "macro_precision": round(float(macro_p), 4),
        "macro_recall": round(float(macro_r), 4),
        "macro_f1": round(float(macro_f1), 4),
        "per_class_f1": {l: round(per_class[l]["f1-score"], 4) for l in present_names},
        "confusion_matrix": cm,
        "labels_order": present_names,
    })

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(result, indent=2))
    print(f"\nSaved report to {report_path}")


if __name__ == "__main__":
    sys.exit(main())
